import test from 'node:test';
import assert from 'node:assert/strict';
import { makeRoom, call, ENV, memoryStorage } from './helpers.js';
import { signToken } from '../src/auth.js';
const time = 1780000000000;
const path = '/s/launcher/';
const adminId = '76561198064130816', secondAdmin = '76561198267601141', playerId = '76561198000000123';
async function setup() {
  const storage = memoryStorage();
  const room = makeRoom({ clock: { value: time }, storage });
  const token = (sid) => signToken({ sid, name: 'Same nick', exp: time+100000 }, ENV.TOKEN_SECRET);
  return { storage, admin: await token(adminId), admin2: await token(secondAdmin), player: await token(playerId), req: (method, suffix, token, body) => call(room, method, path+suffix, { token, body }) };
}
test('Steam roles gate news and admin routes; published news is public', async () => {
  const { req, admin, admin2, player } = await setup();
  assert.equal((await req('GET','account',admin2)).body.admin,true);
  assert.equal((await req('GET','account',player)).body.admin,false);
  assert.equal((await req('POST','news',player,{ title:'Test',text:'Text' })).status,403);
  assert.equal((await req('POST','news',undefined,{ title:'Test',text:'Text' })).status,401);
  assert.equal((await req('POST','news',admin,{ title:'Test',text:'Line 1\nLine 2' })).status,201);
  const [item] = (await req('GET','news')).body.items;
  assert.equal(item.text,'Line 1\nLine 2');
  assert.equal((await req('POST','moderation/news/delete',player,{ id:item.id })).status,403);
  assert.equal((await req('POST','moderation/news/delete',admin2,{ id:item.id })).status,200);
  assert.deepEqual((await req('GET','news')).body.items,[]);
});
test('streams publish immediately, reject invalid URLs, and delete globally', async () => {
  const { req, admin, player } = await setup();
  assert.equal((await req('POST','streams',null,{url:'https://youtu.be/dQw4w9WgXcQ'})).status,401);
  assert.equal((await req('POST','streams',player,{url:'https://www.youtube.com/redirect?q=https://evil.test'})).status,400);
  assert.equal((await req('POST','streams',player,{url:'https://youtu.be/dQw4w9WgXcQ?t=2'})).status,201);
  const [item] = (await req('GET','streams')).body.items;
  assert.equal(item.url,'https://www.youtube.com/watch?v=dQw4w9WgXcQ');
  assert.equal((await req('POST','streams',player,{url:item.url})).status,409);
  assert.equal((await req('POST','moderation/streams/delete',player,{id:item.id})).status,403);
  assert.equal((await req('POST','moderation/streams/delete',admin,{id:item.id})).status,200);
  assert.deepEqual((await req('GET','streams')).body.items,[]);
});
test('author identities are admin-only; deletion and bans apply server-side', async () => {
  const { req, storage, admin, player } = await setup();
  await storage.put('msg:000000000001', { seq:1, name:'Legacy',text:'old',time,source:'launcher' });
  await storage.put('meta', { seq:1 });
  await req('POST','chat',player,{text:'New'});
  const list = (await req('GET','chat?latest=1',admin)).body.messages;
  assert.equal(list[0].steamId,undefined);
  assert.equal(list[1].steamId,playerId);
  assert.equal((await req('GET','chat?latest=1',player)).body.messages[1].steamId,undefined);
  assert.equal((await req('GET','moderation/authors',player)).status,403);
  assert.equal((await req('GET','moderation/authors',admin)).body.authors[0].name,'Same nick');
  const ban = (token,minutes) => req('POST','moderation/chat/ban',token,{steamId:playerId,minutes});
  assert.equal((await ban(player,5)).status,403);
  assert.equal((await ban(admin,5)).status,200);
  assert.equal((await req('POST','chat',player,{text:'Blocked'})).body.error,'banned');
  assert.equal((await req('GET','moderation/authors',admin)).body.authors[0].bannedUntil,time+300000);
  assert.equal((await ban(admin,0)).status,200);
  assert.equal((await req('GET','moderation/authors',admin)).body.authors[0].bannedUntil,null);
  assert.equal((await req('POST','moderation/chat/delete',player,{seq:2})).status,403);
  await req('POST','moderation/chat/delete',admin,{seq:2});
  assert.equal((await req('GET','chat?latest=1',player)).body.messages.length,1);
});
